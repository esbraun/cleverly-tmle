"""The memory guard of ``LTMLE``, ``SDR`` and ``IPSI`` (X106 part J2d).

Before any learner, :meth:`~cleverly.longitudinal.estimator._SequentialEstimator._preflight`
predicts the peak memory of the whole call from counts known once the plans, the horizons and
the draws are resolved (:class:`FitCounts`), and raises :class:`LongitudinalMemoryError` when
the prediction exceeds ``max_memory_bytes``, or the memory available when that is ``None``.

One draw is predicted as ``c0 + 8 n * sum_k c_k x_k`` over the count terms of :data:`TERMS`,
with one constant set per family (:data:`CONSTANTS`), fitted to ``tracemalloc`` peaks over a
declared grid.  The whole call is

    MARGIN * (repeats * draw + max(workers, bootstrap) + band)

where ``band`` is the simultaneous band's draw buffer (:func:`band_bytes`) and, at ``j > 1``
workers, ``workers = (m(F) - 1) draw + min(j, F) w(F) draw + j WORKER + HELPER`` when the ``F``
outer folds fan out, and ``bootstrap = min(j, B) (draw + panel) + j WORKER + HELPER`` for ``B``
parallel replicates; at one worker a replicate adds one ``draw``.
The prediction counts the arrays the estimator holds with GLM, logistic and linear learners; a
learner's own working memory beyond them is not counted.

The calibration literals (:data:`CONSTANTS`, :data:`WORKER_BYTES`, :data:`HELPER_BYTES`,
:data:`WORKER_SHARE`, :data:`FITTED` and :data:`EXTENSIONS`) are generated by
``tests/diagnostics/x106_j2d_memory/generate.py`` from the calibration's own records, and
``tests/unit/test_longitudinal_memory_guard.py`` checks that they match.
``docs/technical-reference/longitudinal-tmle.md`` ("Memory") states the counts, the ranges and
the evidence.
"""

