#: The factor the prediction is raised by over the fitted constants.  The largest cold
#: resident set over the traced peak in the calibration was 1.32.
MARGIN = 1.35

#: How far the margined prediction may exceed the true peak at one worker, which the refusal
#: states: the largest margined ratio over the fitted and checked cells was 3.31.
FACTOR = 3.5

#: The most workers the worker term was measured at; above it the fit is out of range.
MAX_JOBS = 4

#: The sentence on what the prediction counts, which the refusal and the preview share.
LEARNERS = (
    "The prediction counts the arrays the estimator holds, calibrated with GLM, logistic and "
    "linear learners, and other learners' own memory is not counted."
)


class LongitudinalMemoryError(MethodConfigurationError):  # numpydoc ignore=PR01
    """A longitudinal fit predicted to need more memory than its budget.

    Raised before any learner.  ``predicted`` and ``budget`` are in bytes, ``None`` on a copy
    rebuilt from the refusal alone.
    """

    predicted: int | None = None
    budget: int | None = None


@dataclass(frozen=True)
class FitCounts:
    """The counts the memory guard reads, resolved before any learner.

    Parameters
    ----------
    estimator : str
        The class name the refusal names.
    family : str
        The key of :data:`CONSTANTS`.
    n : int
        Units.
    n_times : int
        Nodes.
    plans : int
        The plans the recursion fits.
    horizons : tuple of int
        The reported horizons; ``(T,)`` at the end of the study.
    causes : int
        Causes, 1 without competing events.
    folds : int
        Outer folds.
    width : int
        Columns of the widest history design.
    bins : int
        Density bins at continuous nodes, 0 without them or on the classifier route.
    msm : bool
        Whether the fit projects on a regimen working model.
    repeats : int
        Draws, every one kept by the result.
    bootstrap : int
        Full-refit bootstrap replicates.
    jobs : int
        The worker count joblib resolves ``n_jobs`` to.
    panel_bytes : int
        Bytes of the prepared panel's arrays, which a parallel replicate copies.
    paths : int or None
        The slots of a path fit whose regimens draw from a known policy, ``None`` otherwise.
    censored : bool
        Whether the panel has censoring.
    markov : bool
        Whether the panel has a Markov order.
    levels : int
        The most treatment levels at any node (2 for a binary treatment).
    simultaneous : bool
        Whether the call builds the simultaneous band (``simultaneous=True``), whose draw
        buffer :func:`band_bytes` counts.
    n_multiplier : int
        The multiplier replicates of the band, which cap its block of draws.
    mixed : bool
        Whether a treatment node is mixed (point masses beside a continuous part).
    """

    estimator: str
    family: str
    n: int
    n_times: int
    plans: int
    horizons: tuple[int, ...]
    causes: int
    folds: int
    width: int
    bins: int
    msm: bool
    repeats: int
    bootstrap: int
    jobs: int
    panel_bytes: int
    paths: int | None = None
    censored: bool = False
    markov: bool = False
    levels: int = 2
    simultaneous: bool = False
    n_multiplier: int = DEFAULT_N_REPLICATES
    mixed: bool = False

    @property
    def steps(self) -> int:
        """The horizon-node pairs the recursion fits: the sum of the reported horizons."""
        return int(sum(self.horizons))


#: The count terms, each a function of :class:`FitCounts`, in units of ``8 n`` bytes.
TERMS: dict[str, Callable[[FitCounts], float]] = {
    "RSJ": lambda c: c.plans * c.steps * c.causes,
    "RT": lambda c: c.plans * c.n_times,
    "RTJ": lambda c: c.plans * c.n_times * c.causes,
    "T": lambda c: c.n_times,
    "TJ": lambda c: c.n_times * c.causes,
    "RHJ": lambda c: c.plans * len(c.horizons) * c.causes,
    "p": lambda c: c.width,
    "Rp": lambda c: c.plans * c.width,
    "Tp": lambda c: c.n_times * c.width,
    "one": lambda c: 1,
    "FRT": lambda c: c.folds * c.plans * c.n_times,
    "FT": lambda c: c.folds * c.n_times,
    "TB": lambda c: c.n_times * c.bins,
    "RTB": lambda c: c.plans * c.n_times * c.bins,
    "FTB": lambda c: c.folds * c.n_times * c.bins,
    "BB": lambda c: c.bins * c.bins,
    "TBB": lambda c: c.n_times * c.bins * c.bins,
    "RS_msm": lambda c: c.plans * c.steps if c.msm else 0,
    "TU": lambda c: c.n_times * (c.paths or 0),
    "TUJ": lambda c: c.n_times * (c.paths or 0) * c.causes,
    "Up": lambda c: (c.paths or 0) * c.width,
}

