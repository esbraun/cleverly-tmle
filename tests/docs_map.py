    """One part of the repository and the pages a change to it can make stale.

    Parameters
    ----------
    name : str
        A short label printed in the report.
    code : tuple of str
        Repository-relative glob patterns (``fnmatch`` syntax, where ``*`` also crosses ``/``).
    pages : tuple of str
        Repository-relative documentation sources to review when the code changes.
    guards : tuple of str, default ()
        Test files that already tie part of these pages to the code.
    see_also : tuple of str, default ()
        Pages the report lists for the reviewer but never fails on. Tutorial notebooks sit here:
        their printed numbers are gated by ``tests/notebook_freshness.py`` and the runtime
        gates, and touching one means re-executing it.
    """

    name: str
    code: tuple[str, ...]
    pages: tuple[str, ...]
    guards: tuple[str, ...] = ()
    see_also: tuple[str, ...] = ()


