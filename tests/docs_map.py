"""Which documentation pages a change to each part of the repository can make stale.

:mod:`tests.docs_impact` reads this map on every pull request: a change to a file that an
:class:`Area` lists under ``code`` flags the area's ``pages``, and the pull request must touch
each flagged page or waive it with a stated reason. The map routes a review; it does not say
which sentence is wrong. ``tests/unit/test_docs_map.py`` keeps it honest both ways: every file
in scope matches an area, every glob matches a file, every page exists, and every reader-facing
page is reachable from some area or listed in :data:`STANDALONE_PAGES` with a reason.

Keep an area narrow. A page gates an area when a change in that code can make a sentence on
the page false: the page describes the behaviour, the options, the output or the refusals of
that code. A page that only mentions the code in passing, or whose facts another test already
gates (a tutorial's printed numbers), goes under ``see_also``: listed for the reviewer, never a
failure. A flag that is almost always waived teaches the reader to waive. Measured on the 60 merges
before this map existed, a merge that changed library code routed to a median of three gating
pages. The removed-name scan in
:mod:`tests.docs_impact` covers the passing mentions: a public name or keyword that a change
removes is searched across every page, whatever the map says.

Facts that a test already ties to the code (settings defaults, inference statuses, refusal
messages, study verdicts, notebook outputs) are named under ``guards``. The checker prints them
so a reviewer knows which part of a page a red test will catch and which part only a reader can.

Standard library only: the ``docs-impact`` CI job runs this without installing the package.
"""

from __future__ import annotations

from dataclasses import dataclass

